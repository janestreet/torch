  let self = globalize_tensor self in
  let index = globalize_tensor index in
  let source = globalize_tensor source in
  [%c.alloc
    ({|CAMLreturn(atg_index_copy_out(%{out : tensor value}, %{self : tensor value}, %{dim : int}, %{index : tensor value}, %{source : tensor value}));|}
     : raw_tensor value)]
  |> wrap_managed_tensor
;;

